#!/usr/bin/env python3
"""Generate a separate S1 verification header; never replace historical limits."""
import argparse
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'ros2_ws/src/so101_arm_bridge'))
from so101_arm_bridge.development_ranges import read_development_ranges, calibration_hash, MAXIMUM_OUTPUT_STEP_RAW

SOURCE=ROOT/'config/home_assistant/arm_ranges.development.json'
HEADER=ROOT/'firmware/stm32_g474_single_arm/Core/Inc/generated_s1_arm_ranges.h'
ROS_COPY=ROOT/'ros2_ws/src/so101_arm_bridge/config/arm_ranges.development.json'


def render(entries,digest):
    lines=['/* Generated by generate_development_ranges.py; verification only. */',
        '#ifndef GENERATED_S1_ARM_RANGES_H','#define GENERATED_S1_ARM_RANGES_H',
        f'#define S1_ARM_PROFILE_SHA256 "{digest}"',
        f'#define S1_ARM_CALIBRATION_HASH 0x{calibration_hash(digest):08X}UL',
        f'#define S1_ARM_MAXIMUM_STEP_RAW {MAXIMUM_OUTPUT_STEP_RAW}U',
        '#define S1_ARM_SERVO_SEAM_VERIFIED 0U']
    for index,arm in enumerate(('LEFT','RIGHT')):
        row=[]
        for e in entries[index*6:index*6+6]:
            row.append('{2048U,%d,{%d,%d},{%d,%d}}'%(e['positive_raw_direction'],e['minimum_unwrapped_raw'],e['maximum_unwrapped_raw'],e['minimum_urad'],e['maximum_urad']))
        lines.append('#define S1_ARM_'+arm+'_LIMITS {'+','.join(row)+'}')
    return '\n'.join(lines+['#endif',''])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true');parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    _,entries,digest=read_development_ranges(SOURCE)
    outputs=((HEADER,render(entries,digest).encode()),(ROS_COPY,SOURCE.read_bytes()))
    for path,expected in outputs:
        if args.write:path.write_bytes(expected)
        elif not path.exists() or path.read_bytes()!=expected:raise SystemExit('stale generated output: '+str(path))
    print('S1 development profile matches host and firmware; hardware motion disabled')


if __name__=='__main__':main()
