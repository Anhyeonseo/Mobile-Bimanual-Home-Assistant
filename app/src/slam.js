export function insideMap(x, y) {
  let inside = false;
  for (let a = 0, b = MAP_OUTLINE.length - 1; a < MAP_OUTLINE.length; b = a++) {
    const [ax, ay] = MAP_OUTLINE[a],
      [bx, by] = MAP_OUTLINE[b];
    if (ay > y !== by > y && x < ((bx - ax) * (y - ay)) / (by - ay) + ax) inside = !inside;
  }
  return inside;
}
export function slamBlocked(x, y, zone = false) {
  if (!insideMap(x, y)) return true;
  if (zone && x > 480 && x < 537 && y > 622 && y < 667) return true;
  return OBSERVATIONS.some((o) => Math.hypot(x - o.x, y - o.y) < 13);
}
